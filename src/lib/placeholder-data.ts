// Helperi za pisanje dugačkog sadržaja u Portable Text formatu (isti format
// koji koristi Sanity), bez ručnog kucanja pune strukture bloka za svaki red.
function h2(text: string) {
  return { _type: "block", style: "h2", children: [{ _type: "span", text }] };
}
function h3(text: string) {
  return { _type: "block", style: "h3", children: [{ _type: "span", text }] };
}
function p(text: string) {
  return { _type: "block", style: "normal", children: [{ _type: "span", text }] };
}
function bullets(items: string[]) {
  return items.map((text) => ({
    _type: "block",
    style: "normal",
    listItem: "bullet" as const,
    level: 1,
    children: [{ _type: "span", text }],
  }));
}
// Paragraf sa jednim ugrađenim linkom (koristi se za prirodno povezivanje ka
// stranicama usluga unutar teksta bloga).
function linkPara(before: string, linkText: string, href: string, after: string) {
  return {
    _type: "block",
    style: "normal",
    markDefs: [{ _type: "link", _key: "l1", href }],
    children: [
      { _type: "span", text: before },
      { _type: "span", text: linkText, marks: ["l1"] },
      { _type: "span", text: after },
    ],
  };
}

